"""Shared helpers for the TamiPami performance benchmarks.

Versions are never hard coded. A benchmark target is a *ref*:

* ``WORKTREE`` (or ``.``) - the current working tree, labeled from ``git describe`` plus ``-dirty``
  when there are uncommitted changes.
* any git tag, branch or commit - checked out into a temporary detached ``git worktree`` and
  imported through ``PYTHONPATH`` so nothing is installed or modified.

Each result file is named after the label (e.g. ``cli_v0.3.4.csv``) and has a ``.meta.json``
sidecar with commit, tags, host hardware and tool versions.
"""
from __future__ import annotations

import contextlib
import csv
import datetime as dt
import json
import os
import platform
import shutil
import subprocess
import sys
import tempfile
from dataclasses import dataclass, field
from pathlib import Path

BENCH_DIR = Path(__file__).resolve().parent
REPO = BENCH_DIR.parent
RESULTS_DIR = BENCH_DIR / "results"
DEFAULT_EXPERIMENTS = REPO / "data" / "metadata" / "experiments.csv"
DEFAULT_DATA_DIR = REPO / "data" / "fastq"
WORKTREE = "WORKTREE"


def git(*args: str, cwd: Path = REPO, check: bool = True) -> str:
    out = subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True)
    if check and out.returncode != 0:
        raise RuntimeError(f"git {' '.join(args)} failed: {out.stderr.strip()}")
    return out.stdout.strip()


def latest_tag() -> str:
    return git("describe", "--tags", "--abbrev=0")


def default_refs() -> list[str]:
    """Most recent release tag, then the working tree."""
    return [latest_tag(), WORKTREE]


@dataclass
class Target:
    """A resolved benchmark target: where the code lives and how it is labeled."""
    ref: str
    label: str
    describe: str
    commit: str
    dirty: bool
    tags: list[str]
    source_dir: Path
    env: dict = field(default_factory=dict)
    _tmp: str | None = None

    def metadata(self) -> dict:
        return {
            "ref": self.ref, "label": self.label, "git_describe": self.describe,
            "commit": self.commit, "dirty": self.dirty, "tags_at_commit": self.tags,
            "tamipami_source": str(self.source_dir),
        }


@contextlib.contextmanager
def resolve_target(ref: str):
    """Yield a Target for ``ref``; clean up any temporary worktree on exit."""
    tmp = None
    if ref in (WORKTREE, "."):
        src = REPO
        commit = git("rev-parse", "HEAD")
        dirty = bool(git("status", "--porcelain", "--untracked-files=no", "--", "tamipami", "pyproject.toml"))
        describe = git("describe", "--tags", "--always")
    else:
        commit = git("rev-parse", f"{ref}^{{commit}}")
        dirty = False
        describe = git("describe", "--tags", "--always", commit)
        tmp = tempfile.mkdtemp(prefix="tamipami_bench_")
        src = Path(tmp) / "src"
        git("worktree", "add", "--detach", str(src), commit)
        # _version.py is generated by setuptools_scm and git-ignored; recreate it for the checkout.
        (src / "tamipami" / "_version.py").write_text(f'__version__ = "{describe}"\n')
    label = describe + ("-dirty" if dirty else "")
    tags = git("tag", "--points-at", commit).split()
    env = os.environ.copy()
    env["PYTHONPATH"] = str(src) + os.pathsep + env.get("PYTHONPATH", "")
    # bbmerge.sh lives next to the interpreter in the conda env; make sure children find it.
    env["PATH"] = str(Path(sys.executable).parent) + os.pathsep + env.get("PATH", "")
    target = Target(ref, label, describe, commit, dirty, tags, src, env)
    try:
        # Confirm the child interpreter really imports the checkout we think it does.
        out = subprocess.run([sys.executable, "-c", "import tamipami;print(tamipami.__file__)"],
                             env=env, capture_output=True, text=True, check=True).stdout.strip()
        if Path(out).resolve().parent != (src / "tamipami").resolve():
            raise RuntimeError(f"tamipami imported from {out}, expected {src / 'tamipami'}")
        yield target
    finally:
        if tmp:
            git("worktree", "remove", "--force", str(Path(tmp) / "src"), check=False)
            shutil.rmtree(tmp, ignore_errors=True)


def _sh(cmd: list[str]) -> str:
    try:
        return subprocess.run(cmd, capture_output=True, text=True, timeout=30).stdout.strip()
    except Exception:
        return ""


def system_info() -> dict:
    import psutil
    info = {
        "platform": platform.platform(), "machine": platform.machine(),
        "python": platform.python_version(),
        "logical_cpus": psutil.cpu_count(), "physical_cpus": psutil.cpu_count(logical=False),
        "memory_gb": round(psutil.virtual_memory().total / 2**30, 1),
    }
    if sys.platform == "darwin":
        hw = _sh(["system_profiler", "SPHardwareDataType"])
        for line in hw.splitlines():
            if ":" in line:
                k, v = (s.strip() for s in line.split(":", 1))
                if k in ("Model Name", "Model Identifier", "Chip", "Total Number of Cores", "Memory"):
                    info[k] = v
        info["macos"] = _sh(["sw_vers", "-productVersion"])
        chrome = _sh(["/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", "--version"])
        if chrome:
            info["chrome"] = chrome
    bbmap = _sh([str(Path(sys.executable).parent / "bbmerge.sh"), "--version"])
    if bbmap:
        info["bbmap"] = " ".join(bbmap.split())[:120]
    return info


def write_meta(path: Path, target: Target, params: dict) -> None:
    meta = target.metadata()
    meta.update({"timestamp_utc": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
                 "params": params, "system": system_info()})
    path.write_text(json.dumps(meta, indent=2) + "\n")


def read_experiments(path: str | Path, data_dir: str | Path = "") -> list[dict]:
    """Read the experiments CSV into normalized dicts with data-dir-joined file paths."""
    with open(path, newline="", encoding="utf-8-sig") as fh:
        rows = list(csv.DictReader(fh))
    out = []
    for r in rows:
        r = {k.strip().lower(): (v or "").strip() for k, v in r.items()}
        for key in ("cont1", "cont2", "exp1", "exp2"):
            if r.get(key) and data_dir:
                r[key] = str(Path(data_dir) / r[key])
        out.append({"experiment": r["experiment"], "enzyme": r["enzyme"],
                    "library": r["control library"], **{k: r[k] for k in ("cont1", "cont2", "exp1", "exp2")}})
    return out
